import type { ImprovementProposal } from '@cs/domain';

// ─── Types ────────────────────────────────────────────────────────────────────

export interface PromptPacket {
  id: string;
  proposalId: string;
  type: 'codex_plan' | 'antigravity_execution';
  context: string;
  evidence: string;
  objective: string;
  constraints: string[];
  affectedFiles: string[];
  acceptanceCriteria: string;
  risks: string[];
  expectedTests: string[];
  generatedAt: string;
  /** Ready-to-paste markdown prompt string */
  markdown: string;
}

// ─── In-memory store (demo mode — in production, back with DB) ────────────────

const packetStore = new Map<string, PromptPacket>();

// ─── Core generator ───────────────────────────────────────────────────────────

/**
 * Generate a PromptPacket from an ImprovementProposal.
 *
 * For `codex_plan`: detailed, multi-file, architectural context suitable for Codex.
 * For `antigravity_execution`: focused, scoped, direct execution prompt.
 */
export function generatePacketFromProposal(
  proposal: ImprovementProposal,
  type: 'codex_plan' | 'antigravity_execution',
): PromptPacket {
  const id = `pp-${type}-${proposal.id}-${Date.now()}`;
  const generatedAt = new Date().toISOString();

  const evidence = proposal.evidence.length > 0
    ? proposal.evidence.join('\n- ')
    : 'No direct evidence attached — infer from context.';

  const constraints: string[] = [
    'Stay within the stated write scope.',
    'Do not modify files outside the affected components list.',
    'All changes must remain TypeScript-strict compliant.',
    'No new runtime dependencies without explicit approval.',
    ...buildStrategicConstraints(proposal),
  ];

  const risks: string[] = [
    `Risk level declared by analyst: **${proposal.riskLevel.toUpperCase()}**`,
    `Stated risk: ${proposal.risk}`,
    ...(proposal.rollbackPlan ? [`Rollback plan: ${proposal.rollbackPlan}`] : []),
  ];

  const expectedTests: string[] = buildExpectedTests(proposal);

  const packet: Omit<PromptPacket, 'markdown'> = {
    id,
    proposalId: proposal.id,
    type,
    context: proposal.context,
    evidence,
    objective: proposal.expectedImpact,
    constraints,
    affectedFiles: proposal.affectedComponents,
    acceptanceCriteria: proposal.acceptanceCriteria.join('\n- '),
    risks,
    expectedTests,
    generatedAt,
  };

  const markdown = type === 'codex_plan'
    ? buildCodexPlanPrompt(proposal, packet as PromptPacket)
    : buildAntigravityPrompt(proposal, packet as PromptPacket);

  const full: PromptPacket = { ...packet, markdown };
  packetStore.set(id, full);
  return full;
}

