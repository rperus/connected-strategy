// ─── Helpers ──────────────────────────────────────────────────────────────────

function buildStrategicConstraints(proposal: ImprovementProposal): string[] {
  const flags: string[] = [];
  const m = proposal.strategicMapping;
  if (m.raisesWTP) flags.push('Must demonstrably raise WTP (willingness to pay).');
  if (m.reducesCost) flags.push('Must reduce operational cost — verify with metrics.');
  if (m.increasesSwitchingCosts) flags.push('Must increase switching costs — data lock or habit formation.');
  if (m.improvesActivitySystem) flags.push('Must improve internal activity system fit.');
  if (m.strengthensBusinessModel) flags.push('Must strengthen the business model — document how.');
  return flags;
}

function buildStrategicFlagsMd(proposal: ImprovementProposal): string {
  const m = proposal.strategicMapping;
  return [
    `- Raises WTP: ${m.raisesWTP ? '✅ YES' : '❌ No'}`,
    `- Reduces Cost: ${m.reducesCost ? '✅ YES' : '❌ No'}`,
    `- Increases Switching Costs: ${m.increasesSwitchingCosts ? '✅ YES' : '❌ No'}`,
    `- Improves Activity System: ${m.improvesActivitySystem ? '✅ YES' : '❌ No'}`,
    `- Strengthens Business Model: ${m.strengthensBusinessModel ? '✅ YES' : '❌ No'}`,
    `- Sense/Transmit Phase: **${m.senseTransmitPhase}**`,
    `- Recognize/Request Phase: **${m.recognizeRequestPhase}**`,
  ].join('\n');
}

function buildExpectedTests(proposal: ImprovementProposal): string[] {
  const tests: string[] = [];
  const type = proposal.changeType;

  tests.push('pnpm --filter <affected-package> typecheck');

  if (type === 'feature' || type === 'ui') {
    tests.push('Visual inspection: render the new feature and confirm it matches acceptance criteria.');
    tests.push('No console errors in browser devtools.');
  }
  if (type === 'architecture' || type === 'infra') {
    tests.push('pnpm build — full monorepo build must pass.');
    tests.push('Health endpoint returns ok after changes.');
  }
  if (type === 'data') {
    tests.push('Data migration script runs without errors.');
    tests.push('Read-back verify: data written is correctly retrieved.');
  }
  if (type === 'process') {
    tests.push('End-to-end workflow walkthrough: complete the process described in acceptance criteria.');
  }
  if (type === 'docs') {
    tests.push('All referenced files exist and links are valid.');
  }

  // Always add acceptance criteria as tests
  for (const cr of proposal.acceptanceCriteria) {
    tests.push(cr);
  }

  return tests;
}
