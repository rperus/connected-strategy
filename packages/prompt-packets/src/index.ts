/**
 * Convert a PromptPacket to a ready-to-paste markdown string.
 * The packet already contains .markdown — this function is an explicit re-render.
 */
export function toMarkdown(packet: PromptPacket): string {
  return packet.markdown;
}

/**
 * Retrieve a previously generated packet by ID.
 */
export function getPacketById(id: string): PromptPacket | undefined {
  return packetStore.get(id);
}

/**
 * List all packets generated in this session.
 */
export function listPackets(): PromptPacket[] {
  return [...packetStore.values()];
}

// ─── Codex plan prompt builder ────────────────────────────────────────────────

function buildCodexPlanPrompt(
  proposal: ImprovementProposal,
  packet: PromptPacket,
): string {
  const strategicFlags = buildStrategicFlagsMd(proposal);

  return `# CODEX_PLAN_PROMPT

> **Generated by:** @cs/prompt-packets — Connected Strategy Platform
> **Packet ID:** \`${packet.id}\`
> **Proposal ID:** \`${packet.proposalId}\`
> **Generated at:** ${packet.generatedAt}

---

## Role

You are an expert software architect and connected strategy engineer. You will produce a **structured implementation plan** for the following improvement proposal. Do not write code yet — produce a plan with clear phases, file list, and verification steps.

---

## Context

${packet.context}

---

## Evidence

- ${packet.evidence}

---

## Objective

${packet.objective}

---

## Strategic Mapping

${strategicFlags}

---

## Affected Files / Components

${packet.affectedFiles.length > 0
  ? packet.affectedFiles.map((f) => `- \`${f}\``).join('\n')
  : '- *(to be determined during planning)*'}

---

## Constraints

${packet.constraints.map((c) => `- ${c}`).join('\n')}

---

## Acceptance Criteria

- ${packet.acceptanceCriteria}

---

## Risks

${packet.risks.map((r) => `- ${r}`).join('\n')}

---

## Expected Tests

${packet.expectedTests.length > 0
  ? packet.expectedTests.map((t) => `- [ ] ${t}`).join('\n')
  : '- [ ] At minimum: typecheck must pass after changes\n- [ ] At minimum: existing tests must not regress'}

---

## Required Deliverable

Produce a **phased implementation plan** with:

1. **Phase breakdown** (e.g., Phase 1: Setup, Phase 2: Core logic, Phase 3: Integration, Phase 4: Verification)
2. **File list** (create / modify / delete per phase)
3. **Key decisions** that need to be made before implementation
4. **Verification commands** to run after each phase
5. **Rollback procedure** if implementation fails

${proposal.validationPlan ? `\n## Validation Plan (from analyst)\n\n${proposal.validationPlan}\n` : ''}

---

*This prompt was generated by the Connected Strategy Platform. Paste it directly into Codex.*
`;
}

