/**
 * Convert any report object to a complete, print-friendly HTML string.
 * Includes @media print CSS rules for PDF export.
 */
export function exportToHtml(report: AnyReport): string {
  const sections = report.sections.map((s) => renderSectionHtml(s)).join('\n');

  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1.0" />
  <meta name="description" content="${escapeHtml(report.meta.title)} — Connected Strategy report" />
  <title>${escapeHtml(report.meta.title)}</title>
  <style>
${SCREEN_CSS}
${PRINT_CSS}
  </style>
</head>
<body>
  <div class="report-container">
    <header>
      <h1>${escapeHtml(report.meta.title)}</h1>
      <p class="meta">
        Type: <strong>${report.meta.type}</strong> &nbsp;|&nbsp;
        Generated: <strong>${formatDate(report.meta.generatedAt)}</strong> &nbsp;|&nbsp;
        Template: <code>${escapeHtml(report.meta.templateId)}</code> &nbsp;|&nbsp;
        Version: <code>${escapeHtml(report.meta.generatorVersion)}</code>
      </p>
    </header>

    <main>
${sections}
    </main>

    <footer>
      Generated by @cs/reporting v${escapeHtml(report.meta.generatorVersion)} &mdash; Connected Strategy Platform
    </footer>
  </div>
</body>
</html>`;
}

function renderSectionHtml(section: ReportSection): string {
  const content = renderSectionContentHtml(section);
  return `    <div class="section-card">
      <h2>${escapeHtml(section.title)}</h2>
      ${content}
    </div>`;
}

function renderSectionContentHtml(section: ReportSection): string {
  const c = section.content as Record<string, unknown>;
  if (!c) return '<p><em>No content.</em></p>';

  switch (section.id) {
    case 'executive-summary': {
      const rows = Object.entries(c)
        .filter(([, v]) => !Array.isArray(v) && typeof v !== 'object')
        .map(
          ([k, v]) =>
            `<tr><th>${escapeHtml(formatKey(k))}</th><td>${escapeHtml(String(v))}</td></tr>`,
        )
        .join('\n');
      const arrays = Object.entries(c).filter(([, v]) => Array.isArray(v));
      const arrayHtml = arrays
        .map(
          ([k, v]) =>
            `<h3>${escapeHtml(formatKey(k))}</h3><ul>${(v as unknown[])
              .map((item) => {
                if (typeof item === 'object' && item !== null) {
                  return `<li>${Object.values(item as Record<string, unknown>)
                    .map((x) => escapeHtml(String(x)))
                    .join(' — ')}</li>`;
                }
                return `<li>${escapeHtml(String(item))}</li>`;
              })
              .join('')}</ul>`,
        )
        .join('\n');
      return `<table>${rows}</table>${arrayHtml}`;
    }

    case 'scoring-breakdown': {
      const metrics = c['metrics'] as Array<{
        name: string; score: number; formula: string; rationale: string;
        inputs: Record<string, number>;
      }>;
      if (!metrics) return '';
      const rows = metrics
        .map(
          (m) =>
            `<tr>
              <td>${escapeHtml(m.name)}</td>
              <td class="score-num">${m.score}</td>
              <td class="score-bar">${scoreBar(m.score)}</td>
            </tr>`,
        )
        .join('\n');
      const details = metrics
        .map(
          (m) =>
            `<h3>${escapeHtml(m.name)}</h3>
            <blockquote>${escapeHtml(m.rationale)}</blockquote>
            <p>Formula: <code>${escapeHtml(m.formula)}</code></p>`,
        )
        .join('\n');
      return `<table><thead><tr><th>Dimension</th><th>Score</th><th>Bar</th></tr></thead><tbody>${rows}</tbody></table>${details}`;
    }

    case 'worksheet-completion': {
      const wss = c['worksheets'] as Array<{
        worksheetTitle: string; answeredCount: number; totalQuestions: number;
        completedAt: string | undefined;
      }>;
      if (!wss) return '';
      const rows = wss
        .map((w) => {
          const pct = w.totalQuestions > 0
            ? Math.round((w.answeredCount / w.totalQuestions) * 100)
            : 0;
          return `<tr>
            <td>${escapeHtml(w.worksheetTitle)}</td>
            <td>${w.answeredCount}/${w.totalQuestions} (${pct}%)</td>
            <td>${w.completedAt ? formatDate(w.completedAt) : '<em>Pending</em>'}</td>
          </tr>`;
        })
        .join('\n');
      return `<table><thead><tr><th>Worksheet</th><th>Progress</th><th>Completed</th></tr></thead><tbody>${rows}</tbody></table>`;
    }

    case 'improvement-proposals': {
      const props = c['proposals'] as Array<{
        title: string; status: string; riskLevel: string; changeType: string;
      }>;
      if (!props || props.length === 0) return '<p><em>No proposals found.</em></p>';
      const rows = props
        .map(
          (p) =>
            `<tr>
              <td>${escapeHtml(p.title)}</td>
              <td>${escapeHtml(p.status)}</td>
              <td><span class="badge badge-risk-${p.riskLevel}">${escapeHtml(p.riskLevel)}</span></td>
              <td>${escapeHtml(p.changeType)}</td>
            </tr>`,
        )
        .join('\n');
      return `<table><thead><tr><th>Title</th><th>Status</th><th>Risk</th><th>Type</th></tr></thead><tbody>${rows}</tbody></table>`;
    }

    case 'evidence-summary': {
      const raw = c['rawEvidence'] as string[];
      const linked = c['linkedEvidence'] as Array<{
        type: string; reference: string; description: string; confidence: string;
      }>;
      let html = '';
      if (raw && raw.length > 0) {
        html += `<h3>Raw Evidence</h3><ul>${raw.map((e) => `<li>${escapeHtml(e)}</li>`).join('')}</ul>`;
      }
      if (linked && linked.length > 0) {
        const rows = linked
          .map(
            (e) =>
              `<tr><td>${escapeHtml(e.type)}</td><td><code>${escapeHtml(e.reference)}</code></td><td>${escapeHtml(e.confidence)}</td></tr>`,
          )
          .join('\n');
        html += `<h3>Linked Evidence</h3><table><thead><tr><th>Type</th><th>Reference</th><th>Confidence</th></tr></thead><tbody>${rows}</tbody></table>`;
      }
      return html || '<p><em>No evidence attached.</em></p>';
    }

    case 'acceptance-criteria': {
      const criteria = c['criteria'] as string[];
      if (!criteria || criteria.length === 0) return '<p><em>No criteria defined.</em></p>';
      return `<ul>${criteria.map((cr) => `<li>☐ ${escapeHtml(cr)}</li>`).join('')}</ul>`;
    }

    case 'risk-analysis': {
      const riskClass = `badge badge-risk-${String(c['riskLevel'])}`;
      return `
        <p><strong>Risk Level:</strong> <span class="${riskClass}">${escapeHtml(String(c['riskLevel']))}</span></p>
        <p>${escapeHtml(String(c['risk']))}</p>
        ${c['rollbackPlan'] ? `<h3>Rollback Plan</h3><p>${escapeHtml(String(c['rollbackPlan']))}</p>` : ''}
      `;
    }

    case 'project-rankings': {
      const ranked = c['ranked'] as Array<{ projectName: string; strategicAdvantage: number }>;
      if (!ranked) return '';
      const rows = ranked
        .map(
          (r, i) =>
            `<tr><td>${i + 1}</td><td>${escapeHtml(r.projectName)}</td><td class="score-num">${r.strategicAdvantage}</td></tr>`,
        )
        .join('\n');
      return `<table><thead><tr><th>Rank</th><th>Project</th><th>Score</th></tr></thead><tbody>${rows}</tbody></table>`;
    }

    default: {
      // Generic key-value rendering
      const rows = Object.entries(c)
        .map(([k, v]) => {
          const val = Array.isArray(v)
            ? `<ul>${(v as unknown[]).map((x) => `<li>${escapeHtml(JSON.stringify(x))}</li>`).join('')}</ul>`
            : typeof v === 'object' && v !== null
            ? `<pre><code>${escapeHtml(JSON.stringify(v, null, 2))}</code></pre>`
            : escapeHtml(String(v));
          return `<tr><th>${escapeHtml(formatKey(k))}</th><td>${val}</td></tr>`;
        })
        .join('\n');
      return `<table>${rows}</table>`;
    }
  }
}

function escapeHtml(str: string): string {
  return str
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}
