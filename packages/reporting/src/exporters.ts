import type { PortfolioReport, ProjectReport, ProposalReport, ReportSection } from './types.js';

// ─── Shared helpers ───────────────────────────────────────────────────────────

type AnyReport = PortfolioReport | ProjectReport | ProposalReport;

function scoreBar(score: number): string {
  const filled = Math.round(score / 10);
  return '█'.repeat(filled) + '░'.repeat(10 - filled) + ` ${score}/100`;
}

function formatDate(iso: string): string {
  try {
    return new Date(iso).toLocaleDateString('en-US', {
      year: 'numeric',
      month: 'long',
      day: 'numeric',
    });
  } catch {
    return iso;
  }
}

// ─── Markdown exporter ────────────────────────────────────────────────────────

/**
 * Convert any report object to a readable Markdown string.
 * Suitable for saving as .md files or pasting into docs.
 */
export function exportToMarkdown(report: AnyReport): string {
  const lines: string[] = [];

  lines.push(`# ${report.meta.title}`);
  lines.push('');
  lines.push(`> **Type:** ${report.meta.type} | **Generated:** ${formatDate(report.meta.generatedAt)} | **Template:** \`${report.meta.templateId}\``);
  lines.push('');
  lines.push('---');
  lines.push('');

  for (const section of report.sections) {
    lines.push(`## ${section.title}`);
    lines.push('');
    renderSectionMarkdown(section, lines);
    lines.push('');
  }

  lines.push('---');
  lines.push(`*Generated by @cs/reporting v${report.meta.generatorVersion}*`);

  return lines.join('\n');
}

function renderSectionMarkdown(section: ReportSection, lines: string[]): void {
  const c = section.content as Record<string, unknown>;
  if (!c) return;

  switch (section.id) {
    case 'executive-summary': {
      for (const [key, val] of Object.entries(c)) {
        if (Array.isArray(val)) {
          lines.push(`**${formatKey(key)}:**`);
          for (const item of val as unknown[]) {
            if (typeof item === 'object' && item !== null) {
              const obj = item as Record<string, unknown>;
              lines.push(`- ${Object.values(obj).join(' — ')}`);
            } else {
              lines.push(`- ${String(item)}`);
            }
          }
        } else {
          lines.push(`**${formatKey(key)}:** ${String(val)}`);
        }
      }
      break;
    }

    case 'scoring-breakdown': {
      const metrics = c['metrics'] as Array<{
        name: string; score: number; formula: string; rationale: string;
        inputs: Record<string, number>;
      }>;
      if (metrics) {
        lines.push('| Dimension | Score | Bar |');
        lines.push('|-----------|-------|-----|');
        for (const m of metrics) {
          lines.push(`| ${m.name} | ${m.score} | ${scoreBar(m.score)} |`);
        }
        lines.push('');
        for (const m of metrics) {
          lines.push(`### ${m.name}`);
          lines.push(`- **Score:** ${m.score}/100`);
          lines.push(`- **Formula:** \`${m.formula}\``);
          lines.push(`- **Rationale:** ${m.rationale}`);
          const inputEntries = Object.entries(m.inputs);
          if (inputEntries.length > 0) {
            lines.push('- **Inputs:**');
            for (const [k, v] of inputEntries) {
              lines.push(`  - \`${k}\`: ${v}`);
            }
          }
          lines.push('');
        }
      }
      break;
    }

    case 'worksheet-completion': {
      const wss = c['worksheets'] as Array<{
        worksheetTitle: string; answeredCount: number; totalQuestions: number;
        completedAt: string | undefined;
      }>;
      if (wss) {
        lines.push('| Worksheet | Progress | Completed |');
        lines.push('|-----------|----------|-----------|');
        for (const w of wss) {
          const pct = w.totalQuestions > 0
            ? Math.round((w.answeredCount / w.totalQuestions) * 100)
            : 0;
          lines.push(
            `| ${w.worksheetTitle} | ${w.answeredCount}/${w.totalQuestions} (${pct}%) | ${w.completedAt ? formatDate(w.completedAt) : 'Pending'} |`,
          );
        }
      }
      break;
    }

    case 'improvement-proposals': {
      const props = c['proposals'] as Array<{
        title: string; status: string; riskLevel: string; changeType: string;
      }>;
      if (props && props.length > 0) {
        lines.push('| Title | Status | Risk | Type |');
        lines.push('|-------|--------|------|------|');
        for (const p of props) {
          lines.push(`| ${p.title} | ${p.status} | ${p.riskLevel} | ${p.changeType} |`);
        }
      } else {
        lines.push('*No proposals found.*');
      }
      break;
    }

    case 'evidence-summary': {
      const evidence = c['linkedEvidence'] as Array<{
        type: string; reference: string; description: string; confidence: string;
      }>;
      const raw = c['rawEvidence'] as string[];
      if (raw && raw.length > 0) {
        lines.push('**Raw Evidence:**');
        for (const e of raw) {
          lines.push(`- ${e}`);
        }
        lines.push('');
      }
      if (evidence && evidence.length > 0) {
        lines.push('**Linked Evidence:**');
        lines.push('| Type | Reference | Confidence |');
        lines.push('|------|-----------|------------|');
        for (const e of evidence) {
          lines.push(`| ${e.type} | ${e.reference} | ${e.confidence} |`);
        }
      }
      break;
    }

    case 'acceptance-criteria': {
      const criteria = c['criteria'] as string[];
      if (criteria) {
        for (const cr of criteria) {
          lines.push(`- [ ] ${cr}`);
        }
      }
      break;
    }

    case 'risk-analysis': {
      lines.push(`**Risk Level:** ${String(c['riskLevel'])}`);
      lines.push('');
      lines.push(`**Risk Description:** ${String(c['risk'])}`);
      if (c['rollbackPlan']) {
        lines.push('');
        lines.push(`**Rollback Plan:** ${String(c['rollbackPlan'])}`);
      }
      break;
    }

    case 'project-rankings': {
      const ranked = c['ranked'] as Array<{ projectName: string; strategicAdvantage: number }>;
      if (ranked) {
        lines.push('| Rank | Project | Score |');
        lines.push('|------|---------|-------|');
        ranked.forEach((r, i) => {
          lines.push(`| ${i + 1} | ${r.projectName} | ${r.strategicAdvantage} |`);
        });
      }
      break;
    }

    default: {
      // Generic key-value rendering for all other sections
      for (const [key, val] of Object.entries(c)) {
        if (Array.isArray(val)) {
          lines.push(`**${formatKey(key)}:**`);
          for (const item of val as unknown[]) {
            lines.push(`- ${JSON.stringify(item)}`);
          }
        } else if (typeof val === 'object' && val !== null) {
          lines.push(`**${formatKey(key)}:** (see below)`);
          lines.push('```json');
          lines.push(JSON.stringify(val, null, 2));
          lines.push('```');
        } else {
          lines.push(`**${formatKey(key)}:** ${String(val)}`);
        }
      }
    }
  }
}

function formatKey(key: string): string {
  return key
    .replace(/([A-Z])/g, ' $1')
    .replace(/^./, (s) => s.toUpperCase())
    .trim();
}

